def get_store_dossier(store_name: str) -> Optional[dict[str, str]]:
    """Return a copy of the store dossier dict for *store_name*, or None.

    Accepts an internal store key (e.g. ``'OLG 新宿'``), SEO display name, or
    URL slug via ``store_master`` resolution helpers.
    """
    if not store_name or not isinstance(store_name, str):
        return None
    key = store_name.strip()
    if not key:
        return None
    entry = STORE_DOSSIERS.get(key)
    if entry is None:
        by_slug = store_master.store_by_slug(key)
        if by_slug:
            entry = STORE_DOSSIERS.get(by_slug)
    if entry is None:
        resolved = store_master.to_internal_store_name(key)
        if resolved:
            entry = STORE_DOSSIERS.get(resolved)
    if entry is None:
        return None
    result = dict(entry)
    result.setdefault("editor_credit", EDITOR_CREDIT)
    return result
