def get_tip_for_slot(slot_label: str = "12:00", tip_index: int = None) -> str:
    """
    Select an appropriate tip based on the day of the year and slot.
    Ensures a smooth, non-repeating rotation across all 60 tips.
    """
    now_jst = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=9)))

    if tip_index is not None and 0 <= tip_index < len(TIPS_LIST):
        idx = tip_index
    else:
        # Determine slot offset (12:00 -> 0, 18:00 -> 1)
        slot_offset = 0 if slot_label == "12:00" else 1
        day_of_year = now_jst.timetuple().tm_yday
        idx = (day_of_year * 2 + slot_offset) % len(TIPS_LIST)

    raw_tip = TIPS_LIST[idx].strip()
    site_url = os.environ.get("PUBLIC_SITE_URL", "https://aiseki-navi.com").rstrip("/")

    # Take advantage of X Premium (no 140-char limit): enrich with authoritative guide links & live tool URL
    if slot_label == "12:00":
        link_footer = (
            f"\n\n📖【2026最新】オリラジ・ag・JIS 3大ブランドの違い徹底比較はこちら👇\n"
            f"{site_url}/guide/brand-comparison\n\n"
            f"👇全国80店舗の今わかるリアルタイム人数ランキング\n"
            f"{site_url}/"
        )
    else:  # 18:00
        link_footer = (
            f"\n\n📖【平日攻略】水曜・木曜20時〜22時が最強の穴場である理由はこちら👇\n"
            f"{site_url}/guide/weekday-strategy\n\n"
            f"👇今夜のリアルタイム女性人数＆男女比ランキング\n"
            f"{site_url}/"
        )

    return f"{raw_tip}{link_footer}"


def run_scheduled_tip_post(slot_label: str = "12:00", force: bool = False, tip_index: int = None) -> dict:
    """
    Execute daily tip posting to X (Twitter).
    slot_label: '12:00' or '18:00'
    """
    now_jst = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=9)))
    dedup_key = f"{now_jst.strftime('%Y-%m-%d')}_tip_{slot_label}"
    lock_file = "/tmp/aiseki_navi_last_x_tip.txt"

    if not force:
        try:
            if os.path.exists(lock_file):
                with open(lock_file, "r") as f:
                    if f.read().strip() == dedup_key:
                        logger.info(f"X tip post already sent for {dedup_key}, skipping.")
                        return {"status": "skipped", "reason": "Already posted for this slot today"}
        except Exception:
            pass

    text = get_tip_for_slot(slot_label=slot_label, tip_index=tip_index)
    if not text:
        return {"status": "error", "detail": "Empty tip text"}

    # If force is true or off-hour test, add subtle invisible variation to prevent 403 duplicate
    if force:
        text = f"{text}\n(⏱️{now_jst.strftime('%H:%M:%S')})"

    result = x_poster.post_to_x(text)
    if result.get("status") == "success" and not force:
        try:
            with open(lock_file, "w") as f:
                f.write(dedup_key)
        except Exception:
            pass

    result["tweet_text"] = text
    result["slot"] = slot_label
    return result
