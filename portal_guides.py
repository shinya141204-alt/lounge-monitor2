def get_stores_for_area(area_slug, all_stores):
    area = AREA_GUIDES.get(area_slug)
    if not area:
        return []
    kws = area['keywords']
    parent_slug = area.get('parent_area')
    matched = []
    for s in all_stores:
        sname = s.get('name', '')
        info = store_master.get(sname)
        hit = False
        if info is not None:
            master_area = info.get('area_slug')
            if parent_slug:
                # 細分化都市スラッグ（umeda, namba, yokohama, omiya, sapporo, sendai, hiroshima）:
                # 親エリアに属することを前提に（他地域の誤マッチ防止）、店舗名または表示名で都市キーワード照合
                if master_area in (area_slug, parent_slug):
                    disp = info.get('display_name', '')
                    if any(k in sname or k in disp for k in kws):
                        hit = True
            else:
                # 親・広域エリアスラッグ: store_master の area_slug を厳密に正とする（例: 錦糸町が名古屋の錦に誤爆しない）
                if master_area == area_slug:
                    hit = True
        elif any(k in sname for k in kws):
            hit = True
        if hit:
            s_copy = dict(s)
            tot = int(s_copy.get('women') or 0) + int(s_copy.get('men') or 0)
            h_info = store_hours.get_business_hours_status(sname, total_guests=tot)
            s_copy['slug'] = store_master.slug_of(sname)
            s_copy['seo_name'] = store_master.seo_name(sname)
            s_copy['is_open_now'] = h_info['is_open_now']
            s_copy['today_hours_label'] = h_info['today_hours_label']
            s_copy['hours_label'] = h_info['hours_label']
            s_copy['hours_spec'] = h_info['schedule_spec']
            matched.append(s_copy)
    matched.sort(key=lambda x: (x.get('women', 0), x.get('men', 0), bool(x.get('is_open_now'))), reverse=True)
    return matched
